#!/usr/bin/env python3
"""Combine reviewed events and discovery metadata into a file://-friendly JS snapshot."""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build():
    payload = {}
    for key, name in (("events", "events.json"), ("discovery", "discovery.json"), ("scan", "scan_status.json")):
        payload[key] = json.loads((ROOT / "data" / name).read_text(encoding="utf-8"))
    # Prevent accidental script termination from source-derived RSS text.
    serialized = json.dumps(payload, ensure_ascii=True, separators=(",", ":"))
    serialized = serialized.replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    output = "/* Generated by scripts/build_snapshot.py. Edit events.json, not this file. */\nwindow.ROME_MONITOR_DATA = " + serialized + ";\n"
    (ROOT / "data" / "snapshot.js").write_text(output, encoding="utf-8")
    return payload


if __name__ == "__main__":
    data = build()
    print(f"Built snapshot: {len(data['events'])} reviewed events, {len(data['discovery'])} unreviewed mentions")
